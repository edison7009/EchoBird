export function SmartRouterIcon({ name, size = 22 }: { name?: string | null; size?: number }) {
  const Icon =
    name && Object.prototype.hasOwnProperty.call(smartRouterIcons, name)
      ? smartRouterIcons[name as keyof typeof smartRouterIcons]
      : Waypoints;
  return <Icon size={size} aria-hidden="true" />;
}
